/**
 * Regenerate src/data/countries.js from libphonenumber-js metadata.
 *
 * Run: node scripts/generate-countries.js
 *
 * Names are baked into the output rather than resolved with Intl.DisplayNames
 * at runtime, so the prerendered HTML and the browser can never disagree on
 * option text or sort order.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { getCountries, getCountryCallingCode } from 'libphonenumber-js/max';

// Surfaced in a "Common" optgroup. Chosen from the countries that actually
// appear in Search Console traffic, most frequent first.
const COMMON = ['ZA', 'US', 'GB', 'AU', 'DE', 'NL', 'FR', 'PT', 'BR', 'ID'];

const displayName = new Intl.DisplayNames(['en'], { type: 'region' });

const all = getCountries()
  .map((iso) => ({ iso, dial: getCountryCallingCode(iso), name: displayName.of(iso) || iso }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));

const common = COMMON.map((c) => all.find((x) => x.iso === c)).filter(Boolean);
const rest = all.filter((c) => !COMMON.includes(c.iso));
const rows = (list) => list.map((c) => `  ["${c.iso}", "${c.dial}", ${JSON.stringify(c.name)}],`).join('\n');

const out = `// Generated by scripts/generate-countries.js. Do not edit by hand.
// Names are baked in rather than resolved via Intl.DisplayNames at runtime so
// the prerendered HTML and the browser always agree on option text and order.

/** @type {Array<[iso: string, dialCode: string, name: string]>} */
export const COMMON_COUNTRIES = [
${rows(common)}
];

/** @type {Array<[iso: string, dialCode: string, name: string]>} */
export const OTHER_COUNTRIES = [
${rows(rest)}
];

export const ALL_COUNTRIES = [...COMMON_COUNTRIES, ...OTHER_COUNTRIES];

/** Dial code lookup, e.g. dialFor("ZA") === "27". */
export const dialFor = (iso) => ALL_COUNTRIES.find(([c]) => c === iso)?.[1] ?? '';
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '../src/data/countries.js');
writeFileSync(target, out);
console.log(`wrote ${target} (${common.length} common, ${rest.length} other)`);
